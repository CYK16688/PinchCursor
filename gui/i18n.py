_current_locale = DEFAULT_LOCALE


def current_locale() -> str:
    return _current_locale


def set_locale(value: object) -> str:
    """Change only process-local presentation state; persistence is caller-owned."""
    global _current_locale
    _current_locale = normalize_locale(value)
    return _current_locale


def translate(key: str, *, locale: object | None = None, **values: object) -> str:
    """Translate a stable key for an explicit or active supported locale."""
    selected = normalize_locale(current_locale() if locale is None else locale)
    text = _CATALOGS.get(selected, {}).get(key, key)
    try:
        return text.format(**values)
    except (KeyError, ValueError):
        return text


def tr(key: str, **values: object) -> str:
    """Translate using the active process locale."""
    return translate(key, **values)
